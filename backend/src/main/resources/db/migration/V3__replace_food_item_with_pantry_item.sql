-- The legacy food_item table was global (no owner). Ingredients now belong to a user
-- and live either in the fridge or in the cupboard, so the table is recreated.
DROP TABLE IF EXISTS food_item;

CREATE TABLE pantry_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                   NOT NULL,
    name       VARCHAR(80)              NOT NULL,
    category   VARCHAR(30)              NOT NULL,
    location   VARCHAR(20)              NOT NULL,
    quantity   NUMERIC(10, 2)           NOT NULL,
    unit       VARCHAR(20)              NOT NULL,
    expires_at DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_pantry_items_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_pantry_items_user_location ON pantry_items (user_id, location);
